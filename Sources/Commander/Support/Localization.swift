    static let isItalian: Bool = {
        if let override = ProcessInfo.processInfo.environment["COMMANDER_LANG"] {
            return override.lowercased().hasPrefix("it")
        }
        let preferred = Locale.preferredLanguages.first?.lowercased() ?? "en"
        return preferred.hasPrefix("it")
    }()

    static func t(_ english: String) -> String {
        guard isItalian else { return english }
        return italian[english] ?? english
    }

    static func items(_ count: Int) -> String {
        if isItalian {
            return count == 1 ? "1 elemento" : "\(count) elementi"
        }
        return count == 1 ? "1 item" : "\(count) items"
    }

    static func selected(_ count: Int) -> String {
        if isItalian {
            return count == 1 ? "1 selezionato" : "\(count) selezionati"
        }
        return count == 1 ? "1 selected" : "\(count) selected"
    }

    static func itemsSelected(_ selected: Int, of total: Int) -> String {
        isItalian
            ? "\(selected) di \(total) selezionati"
            : "\(selected) of \(total) selected"
    }

